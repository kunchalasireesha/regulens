import { randomUUID } from "node:crypto";
import { mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, normalize, sep } from "node:path";

/**
 * Where uploaded files live: local disk in development, Supabase Storage when deployed
 * (supabase-storage.ts), chosen by createFileStorage.
 */
export interface FileStorage {
  /** Stores bytes under key. Writing an existing key is a no-op. */
  put(key: string, bytes: Uint8Array): Promise<void>;
  get(key: string): Promise<Uint8Array>;
}

/** Files are content-addressed: same organization and bytes, same key. */
export function storageKeyFor(organizationId: string, contentHash: string): string {
  return `${organizationId}/${contentHash}.pdf`;
}

export class LocalFileStorage implements FileStorage {
  constructor(private readonly rootDir: string) {}

  async put(key: string, bytes: Uint8Array): Promise<void> {
    const path = this.resolve(key);
    if (await exists(path)) return;
    await mkdir(dirname(path), { recursive: true });
    // Write to a temporary file and rename, so a crash mid-write never leaves a
    // truncated file under the real key.
    const tmp = `${path}.${randomUUID()}.tmp`;
    try {
      await writeFile(tmp, bytes);
      await rename(tmp, path);
    } catch (error) {
      await rm(tmp, { force: true });
      throw error;
    }
  }

  async get(key: string): Promise<Uint8Array> {
    return new Uint8Array(await readFile(this.resolve(key)));
  }

  /** Keys are generated by the server, but reject anything that escapes rootDir anyway. */
  private resolve(key: string): string {
    const relative = normalize(key);
    if (isAbsolute(relative) || relative === ".." || relative.startsWith(`..${sep}`)) {
      throw new Error("Invalid storage key");
    }
    return join(this.rootDir, relative);
  }
}

async function exists(path: string): Promise<boolean> {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}
